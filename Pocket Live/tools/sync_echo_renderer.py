"""Vendor the reviewed Echo renderer without its dataset loader/comparison app."""
import argparse,hashlib,json,re,subprocess
from pathlib import Path
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--source',type=Path,required=True);a=p.parse_args()
out=root/'web/device-renderers/echo';out.mkdir(parents=True,exist_ok=True)
hashes={}
for name in ['parameters.js','model.js','controls.js','pages.js','state.js']:
 text=(a.source/name).read_text();hashes[name]=hashlib.sha256(text.encode()).hexdigest()
 text=text.replace('.js?v=2','.js')
 if name=='pages.js':text=text.replace('<g aria-hidden="true">','<g aria-hidden="true" data-echo-decorative-header>')
 if name=='state.js':
  start=text.index('async function readJson');end=text.index('const concise')
  text=text[:start]+text[end:]
 (out/name).write_text(text)
(out/'index.js').write_text("export {render} from './pages.js';\nexport {format} from './state.js';\nexport {clamp} from './parameters.js';\n")
(out/'provenance.json').write_text(json.dumps({'source':'Echo independent reference challenge, reviewed final pass','files':hashes,'omitted':['dataset loader','comparison harness','demo interactions']},indent=2)+'\n')
# All captured parameters must match before selecting this face for a Live device.
state=json.loads((a.source.parent/'states/14-echo-01-stereo-eighth-linked.json').read_text())
spec={'id':'echo','className':'Echo','bindings':[{k:p[k] for k in ('name','min','max','quantized','items')} for p in state['parameters']]}
(root/'web/echo-signature.js').write_text('// Generated by tools/sync_echo_renderer.py.\nconst EchoSignature='+json.dumps(spec,separators=(',',':'))+';\n')
subprocess.run([str(root/'node_modules/.bin/esbuild'),str(out/'index.js'),'--bundle','--format=iife','--global-name=EchoRenderer','--target=es2020','--outfile='+str(root/'web/echo-renderer.js')],check=True)
print('Vendored Echo renderer:',out)
