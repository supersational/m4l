"""Package the already-reviewed lab model and captured layout without changing its maths."""
from pathlib import Path
import argparse,json,re
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--source',type=Path,required=True,help='Path to the device-ui-lab checkout')
lab=parser.parse_args().source
out=Path(__file__).resolve().parents[1]/'web'
source=(lab/'src/core/graph.js').read_text()
source=re.sub(r'\bexport\s+', '', source)
names=['graphPlugins','responseDb','frequencyX','xFrequency','valueAtFrequency','frequencyAtValue','normalized','clamp','FILTER_DISPLAY']
(out/'filter-model.js').write_text('// Generated by tools/sync_filter_model.py from device-ui-lab/src/core/graph.js.\nconst AutoFilterModel=(()=>{\n'+source+'\nreturn {'+','.join(names)+'};\n})();\n')
template=json.loads((lab/'public/templates/AutoFilter2.json').read_text())
(out/'filter-layout.js').write_text('// Captured layout and parameter signature; regenerate with tools/sync_filter_model.py.\nconst AutoFilterLayout='+json.dumps(template,separators=(',',':'))+';\n')
